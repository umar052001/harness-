package runner

// acpProxyScript relays JSON-RPC frames between this process and a sandboxed
// agent.
//
// It exists because the agent's stdio is the sandbox's stdio, and the control
// plane needs to speak ACP to it without the agent being aware of the sandbox.
// The relay is deliberately dumb: it splits its input on newlines, forwards each
// line, and forwards replies back. It never parses a frame, so it cannot read or
// alter the conversation, and a bug in it cannot corrupt one.
//
// Buffering is the whole design risk. Frame boundaries are newlines, so the
// proxy must not emit a partial line and must not merge two frames. stdout is
// therefore written with a write per line, and backpressure is left to the
// pipes: if the agent stops reading, this process blocks, which is the correct
// outcome.
const acpProxyScript = `
// Generated by the Go control plane. Do not edit in place.
const { spawn } = require("child_process");
const [cmd, ...args] = process.argv.slice(2);
if (!cmd) { process.stderr.write("acp-proxy: no command\n"); process.exit(2); }

const child = spawn(cmd, args, { stdio: ["pipe", "pipe", "inherit"] });

// Forward stdin -> child stdout, one frame at a time.
let buf = "";
process.stdin.setEncoding("utf8");
process.stdin.on("data", (chunk) => {
  buf += chunk;
  let idx;
  while ((idx = buf.indexOf("\n")) >= 0) {
    const line = buf.slice(0, idx + 1);
    buf = buf.slice(idx + 1);
    if (line.trim() === "") continue;
    if (!child.stdin.writableEnded) child.stdin.write(line);
  }
});
process.stdin.on("end", () => {
  if (buf.trim() !== "" && !child.stdin.writableEnded) child.stdin.write(buf);
  child.stdin.end();
});

// Forward child stdout -> our stdout, preserving frame boundaries.
let outBuf = "";
child.stdout.setEncoding("utf8");
child.stdout.on("data", (chunk) => {
  outBuf += chunk;
  let idx;
  while ((idx = outBuf.indexOf("\n")) >= 0) {
    const line = outBuf.slice(0, idx + 1);
    outBuf = outBuf.slice(idx + 1);
    if (line.trim() === "") continue;
    process.stdout.write(line);
  }
});
child.stdout.on("end", () => {
  if (outBuf !== "") process.stdout.write(outBuf);
  process.stdout.end();
});

child.on("error", (e) => {
  process.stderr.write("acp-proxy: " + e.message + "\n");
  process.exit(127);
});
// The agent's exit status is the proxy's exit status, so a caller sees the
// agent's failure rather than a relay failure.
child.on("close", (code, signal) => {
  if (signal) process.kill(process.pid, signal);
  else process.exit(code === null ? 1 : code);
});
`
